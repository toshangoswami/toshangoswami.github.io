const places = [
  { name: "Boston", key: "boston", code: "BOS", date: "07 · 14 · 25" },
  { name: "San Francisco", key: "sf", code: "SFO", date: "03 · 02 · 25" },
  // TODO: Ann Arbor stamp date, in the same MM · DD · YY format
  { name: "Ann Arbor", key: "annarbor", code: "ARB", date: "TODO" },
];
let placeIdx = 0;

function windowHTML(place, mode) {
  const art = mode === 'main' ? `<div class="ink-art">${ART[place.key]}</div>` : '';
  const stamp = mode === 'main' ? `<div class="stamp"><div class="stamp-code">${place.code}</div><div class="stamp-date">${place.date}</div></div>` : '';
  return `
    <div class="wash wc-${place.key}"></div>
    <div class="grain"></div>
    ${art}
    ${stamp}
  `;
}

function renderBehind() {
  // ghost pages: soft color echoes only (no line art) so they never
  // look like a duplicate of whichever city is currently on top
  const other = places[(placeIdx + 1) % places.length];
  document.getElementById('behindA').innerHTML = windowHTML(other, 'ghost');
  document.getElementById('behindB').innerHTML = windowHTML(other, 'ghost');
}

function renderMain() {
  document.getElementById('mainWindow').innerHTML = windowHTML(places[placeIdx], 'main');
  document.getElementById('placeCaption').textContent = places[placeIdx].name;
  renderBehind();
}

function flip(delta) {
  const card = document.getElementById('mainCard');
  card.classList.add('flip-out');
  setTimeout(() => {
    placeIdx = (placeIdx + delta + places.length) % places.length;
    renderMain();
    card.classList.remove('flip-out');
    card.classList.add('flip-in');
    setTimeout(() => card.classList.remove('flip-in'), 280);
  }, 280);
}

function nextPlace() { flip(1); }
function prevPlace() { flip(-1); }

// site.js is shared by every page; only the homepage has the flipbook.
if (document.getElementById('mainWindow')) renderMain();

// Project pages: ←/→ follow the prev/next arrows. Skipped while a video or form
// field has focus (arrows seek a video), and when a modifier is held, so
// browser shortcuts like Alt+← still go back.
const pager = document.querySelector('.project-pager');
if (pager) {
  document.addEventListener('keydown', e => {
    if (e.defaultPrevented || e.altKey || e.ctrlKey || e.metaKey || e.shiftKey) return;
    if (e.target.closest('input, textarea, select, video, [contenteditable]')) return;
    const rel = { ArrowLeft: 'prev', ArrowRight: 'next' }[e.key];
    if (!rel) return;
    e.preventDefault();
    pager.querySelector(`[rel="${rel}"]`).click();
  });
}

// Click-to-play YouTube: swap the poster link for the player only when asked,
// so pages don't load YouTube's scripts up front.
document.querySelectorAll('.yt-facade').forEach(link => {
  link.addEventListener('click', e => {
    e.preventDefault();
    const frame = document.createElement('iframe');
    frame.src = `https://www.youtube-nocookie.com/embed/${link.dataset.yt}?autoplay=1`;
    frame.title = link.dataset.title;
    frame.allow = 'autoplay; encrypted-media; picture-in-picture; fullscreen';
    frame.allowFullscreen = true;
    link.replaceWith(frame);
    frame.focus();
  });
});
