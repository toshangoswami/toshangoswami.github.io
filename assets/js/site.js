const places = [
  { name: "Boston", key: "boston", code: "BOS", date: "07 · 14 · 25" },
  { name: "San Francisco", key: "sf", code: "SFO", date: "03 · 02 · 25" },
];
let placeIdx = 0;

function windowHTML(place, mode) {
  const art = mode === 'main' ? `<div class="ink-art">${ART[place.key]}</div>` : '';
  const stamp = mode === 'main' ? `<div class="stamp"><div class="stamp-code">${place.code}</div><div class="stamp-date">${place.date}</div></div>` : '';
  return `
    <div class="wash wc-${place.key}"></div>
    <div class="grain"></div>
    ${art}
    ${stamp}
  `;
}

function renderBehind() {
  // ghost pages: soft color echoes only (no line art) so they never
  // look like a duplicate of whichever city is currently on top
  const other = places[(placeIdx + 1) % places.length];
  document.getElementById('behindA').innerHTML = windowHTML(other, 'ghost');
  document.getElementById('behindB').innerHTML = windowHTML(other, 'ghost');
}

function renderMain() {
  document.getElementById('mainWindow').innerHTML = windowHTML(places[placeIdx], 'main');
  document.getElementById('placeCaption').textContent = places[placeIdx].name;
  renderBehind();
}

function flip(delta) {
  const card = document.getElementById('mainCard');
  card.classList.add('flip-out');
  setTimeout(() => {
    placeIdx = (placeIdx + delta + places.length) % places.length;
    renderMain();
    card.classList.remove('flip-out');
    card.classList.add('flip-in');
    setTimeout(() => card.classList.remove('flip-in'), 280);
  }, 280);
}

function nextPlace() { flip(1); }
function prevPlace() { flip(-1); }

renderMain();

function toggleWorkMenu(e) {
  e.stopPropagation();
  const menu = document.getElementById('workMenu');
  const btn = document.getElementById('workToggle');
  const willOpen = menu.classList.contains('hidden');
  menu.classList.toggle('hidden');
  btn.setAttribute('aria-expanded', String(willOpen));
}

function closeWorkMenu() {
  document.getElementById('workMenu').classList.add('hidden');
  document.getElementById('workToggle').setAttribute('aria-expanded', 'false');
}

document.addEventListener('click', (e) => {
  const menu = document.getElementById('workMenu');
  const btn = document.getElementById('workToggle');
  if (!menu.classList.contains('hidden') && !menu.contains(e.target) && !btn.contains(e.target)) {
    closeWorkMenu();
  }
});
  
function openInspiration() {
  const m = document.getElementById('inspirationModal');
  m.classList.remove('hidden');
  document.body.style.overflow = 'hidden';
  m.querySelector('.modal-close').focus();
}

function closeInspiration() {
  document.getElementById('inspirationModal').classList.add('hidden');
  document.body.style.overflow = '';
}

// close only when the backdrop itself is clicked, not the card
function backdropClose(e) {
  if (e.target.id === 'inspirationModal') closeInspiration();
}

document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape') { closeInspiration(); closeWorkMenu(); }
});
